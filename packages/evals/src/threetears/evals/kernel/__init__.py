"""The engine's kernel: the behaviour every other package runs on, over the shapes in :mod:`threetears.evals.schema`.

Identity and the keys it derives, scoring and the metric catalogue, the goal-check evaluator, the
world session, usage capture, the typed repositories over the document store (:class:`EvalStorage`),
the campaign and analysis documents with the design and decision surface that validate them, and
the candidate kind with its cassette seams. It imports nothing but itself, the schema, pydantic and
:mod:`threetears.observe` (for logging), which is what lets ``run``, ``analysis`` and ``gen`` all
depend on it without depending on each other. The host contract a consuming product declares is the
sibling root :mod:`threetears.evals.kernel.host`.

**This module is the package's public root.** A host imports from here and from no module below
it, and only the names in ``__all__``; ``tests/test_package_matrix.py`` holds that, and
``tests/test_public_surface_is_closed.py`` holds every engine type a public signature hands a host to
being exported from a public root. A ``# debt:`` comment on an export names what retires it. Code
inside the package imports its own modules directly.
"""

