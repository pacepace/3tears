"""The engine's stored shapes and the ports a host implements: what is written down, and what writes it.

Every stored eval document (template, test case, run, result, trace, calibration rating, the
out-of-run spend ledger, the definitions and their tombstones, cassettes, case sets) and the shapes
embedded in them, plus the three ports a host builds and hands in — the document store
(:class:`DocumentStore`), the completion client (:class:`CompletionClient`) and the trace sink
(:class:`TraceSink`). The goal-check grammar is here too, because a stored template validates its
expressions through it.

It imports only itself, pydantic and the standard library (its loggers are :mod:`~threetears.evals.schema.logs`),
and nothing of the engine's behaviour, which lives in :mod:`threetears.evals.kernel`. That is what keeps it small and
slow-moving: an adapter author or a reader in another language finds what they bind to here, and a
change here is a change to what is stored.

**This module is the package's public root.** A host imports from here and from no module below
it, and only the names in ``__all__``; ``tests/test_package_matrix.py`` holds that, and
``tests/test_public_surface_is_closed.py`` holds every engine type a public signature hands a host to
being exported from a public root. Code inside the package imports its own modules directly.
"""

