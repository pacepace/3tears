class GenerationTally(BaseModel):
    """What one generation has sent, spent and been refused so far — kept by the CALLER.

    :func:`generate_analysis` either returns an analysis or raises, and a cancellation unwinds it
    without either, so its return value can describe only the success. A caller that has to record
    how an attempt ENDED — every attempt — hands one of these in and reads it after the
    call, in whatever way the call ended. The generator writes it as each call is sent and as each
    returns, so it is exact at every point the generation can stop.

    Plain ``BaseModel``: the refusals are the validators' messages verbatim, and stripping them
    would record a refusal that is not the one the validator raised.

    **No field constraints, deliberately.** It is written in place by ``+=`` and ``.append`` while a
    paid generation is in flight, so a constraint could only be enforced with ``validate_assignment``,
    which would turn a bookkeeping anomaly into an exception raised between a billed call and the
    analysis it paid for. The bounds belong where the tally is read into a record that crosses a
    boundary: :class:`~threetears.evals.kernel.campaign.EvalAnalysisAttempt` refuses a negative count or
    cost at construction.
    """

    calls: int = Field(default=0, description="Provider calls sent, counted before each is awaited.")
    returned: int = Field(default=0, description="Calls that came back with a result.")
    unreported_cost: int = Field(default=0, description="Returned calls whose provider reported no cost.")
    token_cost: float = Field(default=0.0, description="Dollars reported across every returned call.")
    reported_models: list[str] = Field(default_factory=list, description="The model each returned call ran on.")
    refusals: list[str] = Field(
        default_factory=list,
        description="Each refusal of a finished call's output, in order, naming cells by their full cell_ref.",
    )
    prompt_version: str | None = Field(default=None, description="The assembled prompt's version, once it is known.")

    @property
    def unpriced_calls(self) -> int:
        """Calls sent whose cost was never observed: cut off before a result, or returned with none."""
        return self.calls - self.returned + self.unreported_cost


def refuse_an_unlisted_writer(profile: HostProfile, model: str) -> None:
    """Refuse, before a token is spent, a writer model the host does not allow (#644).

    The host's :attr:`~threetears.evals.kernel.host.profile.HostProfile.analysis_writer_models` names the
    models it trusts to write its analyses. A model off that list is knowable from what the caller already holds,
    so it is refused before the first provider request: nothing is sent and nothing is spent. It is a
    precondition on the caller's request, not on anything a generator said, so no repair could correct it — a
    second call would be the same model refused the same way — and it raises the bare class. A reporter run, which
    measures writers to learn which belong on the list, does not call this.

    Named ``_refuse_`` for the reason :func:`refuse_an_undescribable_arm_table` is: it is not a member of the
    validation chain.

    Args:
        profile: The host whose allowed writers this reads.
        model: The writer model id, as requested or as the host's client resolved its default.

    Raises:
        GenerationError: The host declares a writer list and ``model`` is not on it. Not
            :class:`SoundnessRefusal`, because that class buys a repair this must never buy.
    """
    if (refusal := profile.analysis_writer_refusal(model)) is not None:
        raise GenerationError(refusal)


def refuse_an_undescribable_arm_table(bundle: AnalysisContextBundle) -> None:
    """Refuse, before a token is spent, a bundle in which NO arm can be described.

    The variant index is how both the model and the reader tell arms apart: it is the arm table
    the prompt carries and the join every per-arm surface renders through. When each entry carries
    ``levels_unavailable``, the campaign's arms have keys and no levels, so nothing the memo says
    can name which arm it is about — a generation billed in full for a report whose every
    comparison is anonymous — a vacuous memo, paid for in full.

    That outcome is deterministic from the bundle alone, so it is knowable for free. Refused HERE
    rather than inside the validation chain for the reason the memo-contract precondition is: a
    repair round-trip corrects what a generator CLAIMED, and no claim the model could make would
    repair apparatus. Feeding this back would buy a second full charge to reach the same place.

    **Only the total case.** A campaign with one describable arm is a partial and is generated.
    An EMPTY index is also not this refusal's business — it means the campaign has no observation
    at all.

    **Named ``_refuse_`` rather than ``_reject_``, and the prefix is load-bearing.** Every
    ``_reject_*`` in this module is a member of :func:`_assemble_and_validate`'s chain, and a
    canary refuses one that is defined and never wired — a soundness check the chain skips ships
    dark on a paid generation. This is a PRECONDITION on the caller's evidence, checked before
    anything is sent, so it is deliberately not a chain member and says so in its name.

    Args:
        bundle: The assembled evidence, before the provider is called.

    Raises:
        GenerationError: Not one indexed arm carries levels. Not :class:`SoundnessRefusal`,
            because that class buys the repair this must never buy.
    """
    index = bundle.variant_index
    if not index or any(entry.levels_unavailable is None for entry in index):
        return
    # De-duplicated and sorted: one cause usually covers every arm, and repeating it once per
    # arm buries the remedy under its own restatement.
    causes = sorted({entry.levels_unavailable for entry in index if entry.levels_unavailable})
    raise GenerationError(
        f"campaign '{bundle.campaign_id}' has no describable arm: all {len(index)} variant(s) in the bundle carry a "
        f"key and no levels, so the arm table would join nothing and no comparison the memo makes could say which arm "
        f"it is about. The generation would be billed in full for an anonymous report, so it is refused "
        f"BEFORE the provider call rather than after. This build's variant predicate is v{IDENTITY_VERSION}. "
        + " ".join(f"Why: {cause}." for cause in causes)
        + " Re-run the campaign on this build so its runs record their own lever maps, or generate from a build at "
        "the identity version the runs were stamped under."
    )


async def generate_analysis(
    bundle: AnalysisContextBundle,
    *,
    prompt: str,
    model: str,
    client: CompletionGenerator,
    prompt_id: str,
    bundle_assembled_at: str,
    prompt_version: str | None = None,
    tally: GenerationTally | None = None,
    admit: CallAdmission | None = None,
    profile: HostProfile,
    measuring_writers: bool = False,
) -> tuple[EvalAnalysis, list[EvalInsight]]:
    """Generate one campaign's analysis from its context bundle, in one LLM call or two.

    A refusal of what a FINISHED call produced buys exactly ONE repair round-trip — a
    soundness rejection, an unparseable payload and a missing required field alike; only a
    call the provider CUT SHORT buys none. The refusal is appended to the
    user message and the analysis regenerated, then validated by the identical chain. A
    second refusal raises as the first one used to. The repair is stored on the returned
    analysis (``generation.repair_attempts`` / ``.repaired_refusal``) and its cost is added
    to ``generation.token_cost``, so nothing about it is invisible to a later reader.

    Args:
        bundle: The pre-assembled context bundle — the closed system's evidence.
        prompt: The resolved ``eval_analysis_gen`` system prompt (the caller reads
            it from the prompt registry, so an operator's edits reach here).
        model: The generator model id, recorded as provenance. Resolved by the caller from
            the Analysis Generator system role, or from a per-call override — named here
            by the role rather than by a model id, which would be dated evidence.
        client: The injected model-provider client. The caller builds it (bound to
            ``model``); the generator never constructs one.
        prompt_id: Provenance id for the prompt — the registry key the caller resolved
            ``prompt`` under. Required rather than defaulted: the caller is the one that
            read the registry, so it is the only party that KNOWS which entry produced
            this text, and a default here would record a guess as provenance.
        bundle_assembled_at: When the caller assembled ``bundle`` (ISO-8601), stamped
            immediately before assembly. Recorded on the provenance as the cutoff a re-assembly
            reads the insight ledger as of. Required for the reason ``prompt_id`` is: the bundle
            arrives assembled, so only the caller saw the instant its ledger was read, and
            anything stamped here would be later than that read by however long the caller took
            to reach this call.
        prompt_version: Provenance version; when ``None``, a content hash of the ASSEMBLED
            system prompt — so two edits of the preset are distinguishable in an A/B, and so are
            two hosts whose style picked different registers. Hashing the registry text alone
            would report one version for two prompts that differ in what they told the model.
        tally: A caller-owned record of what this generation sent, spent and was refused, written as
            it goes so it is exact however the call ends — return, raise or cancellation. The
            caller's record of a FAILED attempt is read from it, since a failure returns nothing.
        admit: Asked with each call's system prompt, user message and contract BEFORE the call is counted
            or sent — the repair round-trip's included, whose prompt exists only once the first output is
            refused. It raises to refuse the call, and the refusal propagates with nothing sent and nothing
            counted for that call. ``None`` admits every call; a caller that prices calls against a cap
            (:func:`~threetears.evals.analysis.service.run_analysis_generation`) passes its budget's.
        profile: The host whose vocabulary this reads, and whose allowed writer models
            (:attr:`~threetears.evals.kernel.host.profile.HostProfile.analysis_writer_models`) ``model`` is
            checked against before anything is sent.
        measuring_writers: True only for a reporter run, which measures writer models to learn which belong on
            that list, so it is not held to it.

    Returns:
        The schema-valid :class:`EvalAnalysis` and the list of
        :class:`EvalInsight` objects it minted (each traced back to this analysis).

    Raises:
        GenerationError: ``model`` is not a writer the host allows (:func:`refuse_an_unlisted_writer`), or the
            bundle describes no arm at all (:func:`refuse_an_undescribable_arm_table`) — nothing is spent, because
            each is knowable from what the caller already holds.
            Or the provider cut the call short (an output-cap
            truncation or a content filter). Not repaired — see :class:`SoundnessRefusal` for
            the boundary and why a truncation in particular must not buy a second charge.
            Note what is NOT in this list any more: a parse failure and a schema failure are
            things a FINISHED call did, so they raise the subclass and buy their repair.
        SoundnessRefusal: The generator's output was refused BOTH times — on the initial call
            and on its repair. Reached from the payload steps (not JSON, a missing or
            wrong-shaped field, a position or reading that points nowhere) as well as from
            the post-generation validators. The causes are deliberately not re-enumerated here, because an
            enumeration drifts every time one is added and this list already had; read the
            chain in :func:`_assemble_and_validate`, where each ``_reject_*`` function
            documents its own. Every one reads a structured field; none reads prose.
    """
    tally = tally if tally is not None else GenerationTally()
    if not measuring_writers:
        refuse_an_unlisted_writer(profile, model)
    refuse_an_undescribable_arm_table(bundle)
    system_prompt, user_message, contract = first_request(bundle, prompt, profile)
    sent_digest = user_message_digest(user_message)
    resolved_prompt_version = (
        prompt_version
        if prompt_version is not None
        else prompt_content_version(prompt, profile, time_axis=bundle.time_axis is not None)
    )
    tally.prompt_version = resolved_prompt_version
    if admit is not None:
        admit(system_prompt, user_message, contract)
    tally.calls += 1
    result = await client.generate(system=system_prompt, user=user_message, response_format=contract)
    _log_generation(bundle, result, model, attempt="initial", tally=tally)

    def _provenance(produced_by: CompletionResult, total_cost: float, *, refusal: str | None) -> GenerationProvenance:
        # ``produced_by`` is the result that actually yielded the STORED analysis, not
        # necessarily the first one: on a repair the provider may echo a different model id
        # (routing moves between calls), and provenance must name what produced the artifact.
        return GenerationProvenance(
            prompt_id=prompt_id,
            prompt_version=resolved_prompt_version,
            generator_model=produced_by.model or model,
            bundle_fingerprint=bundle.fingerprint(),
            generated_at=utc_now_iso(),
            bundle_assembled_at=bundle_assembled_at,
            token_cost=total_cost,
            repair_attempts=0 if refusal is None else 1,
            repaired_refusal=refusal,
            user_message_digest=sent_digest,
            cell_model_version=bundle.cell_model_version,
            bundle_schema_version=bundle.schema_version,
            host_declarations_digest=bundle.host_declarations_digest,
        )

    try:
        return _assemble_and_validate(result, bundle, _provenance(result, tally.token_cost, refusal=None), profile)
    except SoundnessRefusal as refused:
        # Captured because Python unbinds the `except` name at block exit. Two renderings of one
        # refusal: the tally, the log and a failure's summary keep it as code raised it, naming a cell
        # by its full `cell_ref`, because a per-bundle alias means nothing once the record has
        # outlived the bundle it was minted from (the attempt stores only a fingerprint); the repair
        # round and the analysis's provenance get it as the writer was shown cells, by alias,
        # since a writer handed a digest pair can copy it, and that copy is refused too. The stored
        # analysis keeps the surface its aliases were minted from, so its copy stays readable.
        refusal_text = str(refused)
        writer_refusal = in_writer_terms(refusal_text, bundle_decision_surface(bundle))
        tally.refusals.append(refusal_text)
        log.warning(
            "eval.analysis output refused for campaign=%s — attempting ONE repair round-trip "
            "(the first generation was billed $%.4f and is discarded): %s",
            bundle.campaign_id,
            tally.token_cost,
            refusal_text,
        )
    except GenerationError as terminal:
        # Ordering is load-bearing: `SoundnessRefusal` subclasses `GenerationError`, so the
        # subclass clause above must come first or this one swallows every repairable refusal.
        #
        # Reaching HERE means the first call died terminally — a provider-reported truncation or
        # content filter, which buys no repair by design. One billed call, nothing stored, and
        # until now no cost line either: this path raises straight past the repair handler, so
        # the WARNING covering a twice-refused generation never saw it. That left the commonest
        # shape of the very defect this logging exists for — an error sweep returning nothing
        # over a window where money was spent — uncovered.
        summary = (
            f"${format_number(tally.token_cost)} was billed on the one call and nothing was stored. "
            f"No repair was possible: {terminal}"
        )
        log.warning(
            "eval.analysis generation FAILED with no repair possible for campaign=%s model=%s — %s",
            bundle.campaign_id,
            result.model or model,
            summary,
        )
        # The spend rides on the exception for the reason the twice-refused branch below gives:
        # the exception is what crosses the service seam into the 422 an MCP or REST caller
        # reads, and a caller told only that generation failed cannot see that money went with
        # it. Logging it alone left the figure reachable only by an operator who already knew to
        # look — which is the same gap the log line above was added to close, one seam out.
        # Re-raised as the SAME object, and bare, for that branch's reasons: the class is the
        # caller's contract, and a bare `raise` is not a new site for the repair-boundary canary.
        terminal.args = (summary,)
        raise

    # Reached only via the `except` above, since the `try` returns on success. A second
    # refusal propagates from here exactly as the first one used to — one attempt, then fail.
    repair_message = _repair_user_message(
        user_message, writer_refusal, result.content or "(the generator returned no content)"
    )
    if admit is not None:
        admit(system_prompt, repair_message, contract)
    tally.calls += 1
    repair_result = await client.generate(system=system_prompt, user=repair_message, response_format=contract)
    _log_generation(bundle, repair_result, model, attempt="repair", tally=tally)
    try:
        return _assemble_and_validate(
            repair_result, bundle, _provenance(repair_result, tally.token_cost, refusal=writer_refusal), profile
        )
    except GenerationError as exhausted:
        if isinstance(exhausted, SoundnessRefusal):
            # Before the message is replaced below: the tally keeps the refusal itself, not the summary.
            tally.refusals.append(str(exhausted))
        # The third line of a set, and the one that was missing. A FIRST refusal is logged
        # above with its running total; each attempt logs its own cost; a second refusal
        # propagated silently — so a generation billed twice and storing nothing said so
        # nowhere, and an error sweep over a window where a paid generation had just been
        # discarded returned zero entries.
        #
        # WARNING rather than ERROR, matching the first-refusal line: the contract worked —
        # a generation was refused for cause and nothing unsound was stored. What is being
        # reported is spend with nothing to show for it.
        # BOTH models, because the provider may route the two calls differently — `_provenance`
        # says so a few dozen lines up. Naming only the repair's would attribute the first call's
        # spend to the second call's model, and the per-attempt lines that carry it correctly are
        # INFO, which an error sweep does not read.
        #
        # ONE summary, carried by the log line AND the exception. The exception is what crosses
        # the service seam into the 422 a caller reads, and it once
        # carried only the SECOND refusal: the running cost and `refusal_text` are locals here, so the
        # caller of a twice-refused generation was shown the repair's complaint (a headline that
        # named a model) and nothing about the first (an evidence object with no rows) — which can
        # be the same first refusal on repeated generations over one campaign, billed each time,
        # and diagnosable only from the log. The two refusals are usually DIFFERENT
        # rules: the repair fixes what it was told and breaks something else, so a caller holding
        # one of them is holding half the diagnosis.
        summary = (
            f"${format_number(tally.token_cost)} was billed across both calls and nothing was stored. "
            f"First refusal: {refusal_text}. "
            f"Second, after the one repair: {exhausted}{_prompt_provenance_clause(prompt)}"
        )
        log.warning(
            "eval.analysis generation FAILED after one repair for campaign=%s initial_model=%s repair_model=%s — %s",
            bundle.campaign_id,
            result.model or model,
            repair_result.model or model,
            summary,
        )
        # Re-raised as the SAME object with its message replaced, rather than wrapped in a new
        # one: `exhausted` is whichever class the chain raised — a `SoundnessRefusal` for a refused
        # output, the bare class for a repair the provider cut short — and the caller's contract
        # (`test_a_repair_that_truncates_fails_on_the_truncation_not_a_second_refusal`) is that the
        # class survives. A `raise type(exhausted)(...)` would keep the class too, but it is a raise
        # site the repair-boundary canary cannot classify, and a bare `raise` is not a new site.
        exhausted.args = (summary,)
        raise


def _prompt_provenance_clause(prompt: str) -> str:
    """Say, on a twice-refused generation, whether the prompt it ran on is the shipped default.

    The prompt is store-master: :data:`~threetears.evals.analysis.gen_prompt.EVAL_ANALYSIS_GEN_DEFAULT`
    seeds an empty slot once, and after that a rule added to it in code reaches a deployment
    only when an operator pushes it through the host's prompt store. Nothing in a deploy does
    that. So a validator can refuse, at full cost and repeatably, a shape the shipped prompt
    forbids and the deployment's prompt has never heard of — for example a rule like
    ``evidence: null`` shipping in code while the store still serves the older text, so every
    generation over a campaign emits ``{"rows": []}`` and is refused for it. The refusal text named the rule; nothing
    named that the prompt in use predated it, and the diagnosis took reading the store by hand.

    The figure-reference grammar is outside this gap: it is not in the prompt at all, but appended
    by :func:`assemble_system_prompt` from the parser's constants, so a grammar change needs no push.

    This is the disclose-only option — report the divergence and leave the judgement to the operator —
    and deliberately no more: an operator's retuned prompt differs from the default by design, so
    a divergence is a FACT to disclose on a failure, never a reason to refuse or to warn on every
    generation. Compared stripped, because the registry round-trip is not guaranteed to preserve
    a trailing newline and a one-byte difference would report a retuned prompt where there is
    none.

    Args:
        prompt: The resolved registry prompt, as :func:`generate_analysis` received it — the
            body BEFORE the host's style register and caveat kinds are appended, so it is comparable to
            the seed.

    Returns:
        A clause to append to the failure summary, beginning with punctuation. Empty when the
        prompt is the shipped default, so the summary says nothing where there is nothing to say.
    """
    if prompt.strip() == EVAL_ANALYSIS_GEN_DEFAULT.strip():
        return ""
    return (
        ". NOTE: the resolved eval_analysis_gen prompt is NOT the in-repo default — the store is master, so a rule "
        "shipped in gen_prompt.py reaches this deployment only when pushed to the host's prompt store; a refusal "
        "naming a rule the default teaches is the signature of that gap"
    )


def _log_generation(
    bundle: AnalysisContextBundle, result: CompletionResult, model: str, *, attempt: str, tally: GenerationTally
) -> None:
    """Log one returned generation call's cost and token shape, and add it to the tally.

    ``attempt`` distinguishes the initial call from a repair, because otherwise a repaired
    analysis logs two indistinguishable "generated" lines and the repair rate — the whole
    point of recording it — is unreadable from the logs. A call whose provider reported no
    cost adds nothing to the total and is counted as unreported, so the tally does not read
    an unpriced call as a free one.
    """
    cost = result.cost_usd if result.cost_usd is not None else 0.0
    tally.returned += 1
    tally.token_cost += cost
    tally.reported_models.append(result.model or model)
    if result.cost_usd is None:
        tally.unreported_cost += 1
    # `stop_reason` is on the line because it is the only per-attempt record of HOW the
    # call ended. The client logs one WARNING when it maps `finish_reason=length`, but it
    # names the model and nothing else — with two attempts over one campaign, that warning
    # cannot say which attempt truncated, and diagnosing a billed failure meant correlating
    # timestamps across two loggers.
    log.info(
        "eval analysis generated (%s) for campaign=%s: cost=$%.4f prompt_tokens=%s completion_tokens=%s model=%s stop_reason=%s",
        attempt,
        bundle.campaign_id,
        cost,
        # A count the provider did not report is logged as such: ``%d`` would fail on it inside the
        # logging call and lose the whole line, and a ``0`` would claim a measurement.
        "unreported" if result.input_tokens is None else result.input_tokens,
        "unreported" if result.output_tokens is None else result.output_tokens,
        result.model or model,
        result.stop_reason,
    )


def _reject_incomplete_generation(result: CompletionResult) -> None:
    """Refuse a generation the provider itself reported it cut short, before parsing it.

    First in :func:`_assemble_and_validate`, ahead of every parse and every ``_reject_*``,
    and that ordering is the whole point. The output cap is a failure mode a SUPPORTED input
    reaches, not a misuse: ``analysis_generate`` documents ``model`` as an override for
    A/B-ing a cheaper generator, the cap is fixed and the caller cannot raise it, and a model
    whose own output ceiling sits under what the bundle needs truncates every time: it logs
    ``finish_reason=length`` and stores no analysis.

    Placed here rather than at the two call sites because a truncated result must be unable
    to reach the soundness chain, not merely unlikely to: a :class:`SoundnessRefusal` raised
    off a salvaged partial payload buys a repair round-trip, which regenerates into the same
    cap and bills a second full generation to fail the same way. One chokepoint covers the
    initial call and the repair with one check, and a third call site would inherit it.

    **What this does NOT claim.** Nothing here is a timeout or a cancellation — a call that
    sits unanswered is a different failure, upstream of this path — and the case for this
    check does not rest on one: it rests on the truncation being real, on the
    repair boundary having been an unenforced assumption, and on the caller being owed the
    reason for a generation it was billed for.

    Args:
        result: The completed generator call to check.

    Raises:
        GenerationError: The provider reported the call did not finish. Deliberately the
            BARE class and never :class:`SoundnessRefusal` — the call did not finish, so
            there is nothing to feed back that would change the outcome, and the second
            attempt would run into the identical fixed cap.

            **This is now the ONLY thing the bare class means on a call that was made**, and
            this check is the only place that raises it after one. Every other way a
            generation can fail — output that is not JSON, a missing field, an insight
            element that will not build, any ``_reject_*`` validator — is something a
            finished call DID, and raises the repairable subclass. The boundary is
            therefore no longer "which step complained" but "did the call finish", and this
            function is the single place that answers it.
    """
    incomplete = describe_incomplete_completion(result)
    if incomplete is None:
        return
    # `describe_incomplete_completion` names two remedies — raise the cap, or change model — and
    # both are reachable, but not the way it phrases the first: no ACTION takes the cap. It is the
    # host's configured answer budget, which the host's client builder derives the cap from per client. So this SCOPES the shared advice to where the
    # knob actually is; naming a per-call parameter would send an operator hunting for one that does
    # not exist. The budget's value is not restated — it is the host's, and would drift here.
    remedy = (
        " The output cap is not a parameter of this action: it is the host's configured generator answer "
        "budget. Raise that budget, re-run with a larger-output generator model, or narrow the campaign so "
        "there is less to analyse."
        if result.stop_reason == "max_tokens"
        else ""
    )
    raise GenerationError(f"the generator did not finish — {incomplete}{remedy}")


#: Fed back to the generator after a refusal. Deliberately APPENDED to the
#: original user message rather than replacing it: the model needs the same evidence to
#: re-derive the analysis, and putting the new text last keeps the long prefix (system
#: prompt + bundle) byte-identical, which is what a prompt cache matches on.
#:
#: The "do not satisfy it by removing" clause is load-bearing. The cheapest way for a model
#: to satisfy a refusal is to DELETE what was complained about, which turns a repair into
#: silent evidence loss — the report comes back sound and quietly smaller. For example, a
#: generator refused for an ``evidence.rows[]`` coordinate it could not key can return the
#: same analysis with ``evidence.rows`` EMPTY, which `min_length=1` then refuses.
#:
#: The opening two sentences are equally load-bearing and were wrong for a year of a narrower
#: boundary's making: this text asserted "It was complete and well-formed. It was refused for
#: what it CLAIMED", which held while only soundness validators could reach a repair. Once a
#: parse or field failure buys one, telling a model its unparseable output was complete is a
#: false statement in the one prompt whose whole job is to describe accurately what went wrong.
_REPAIR_INSTRUCTION = """

YOUR PREVIOUS ANALYSIS WAS REFUSED, AND THIS IS YOUR ONLY CHANCE TO CORRECT IT.

The call finished, so this is not about length. What came back could not be stored:

{refusal}

Emit the WHOLE analysis again with exactly that corrected. The refusal names what is wrong \
— a rule a claim broke, or a field the payload got wrong — and usually the correct \
alternative. Follow it literally.

Keep everything the refusal does not name. Where your previous output was a complete \
analysis, its other findings, decisions, takeaways and charts were not at issue: reproduce \
them as they were rather than rewriting the report around the fix.

Do NOT satisfy the refusal by REMOVING what it complains about — not the offending finding, \
and not an evidence row or list you are unsure how to key. That answers the refusal by \
losing the result, which is worse than the refusal. The evidence has not changed, so what \
was refused almost always survives in a corrected form: a weaker claim, a different chart \
type, the missing statistic supplied, or the required field copied from the bundle.

THIS IS WHAT YOU SENT, AND IT IS THE ONLY COPY YOU HAVE OF IT:

{previous}"""


def _repair_user_message(user_message: str, refusal: str, previous: str) -> str:
    """Append the refusal AND the refused output to the original user message.

    ``previous`` is included because the refusal often indexes into it and the model cannot
    see it otherwise: the completion port starts a new conversation per call, so the second
    call's only context is what this function builds. A soundness refusal survives that —
    "finding 'f-glm' claimed significance with no statistic" is actionable cold — but the
    parse arm is not: "not valid JSON: Expecting ',' delimiter: line 1 column 34" names a
    coordinate in text the model no longer has, which made the stated justification for
    repairing a parse failure at all untrue of the case it was written for. Cheaper to send
    the output back than to spend a second full generation on a hint that points nowhere.

    Appended LAST so the stable prefix stays as long as it can be. That prefix is the system
    prompt plus the bundle, NOT the instruction: `_REPAIR_INSTRUCTION` interpolates `{refusal}`
    ahead of `{previous}`, and the refusal differs per call, so nothing from the instruction
    onward can be byte-identical to anything. The module comment above the constant says exactly
    this; an earlier version of this docstring claimed the instruction was inside the stable
    prefix, which would have been a reason to order the two fields that does not exist.

    Args:
        user_message: The original bundle message, reused verbatim.
        refusal: The refusal text, which the instruction interpolates.
        previous: The output that was refused.

    Returns:
        The repair call's user message.
    """
    return user_message + _REPAIR_INSTRUCTION.format(refusal=refusal, previous=previous)


def _vocabularies(profile: HostProfile, *, time_axis: bool) -> tuple[frozenset[str], dict[str, str]]:
    """The caveat kinds and chart types on offer — the chart types with how each reads its lists.

    ``timeseries`` is on offer only where the bundle carries a time axis
    (:attr:`~threetears.evals.analysis.bundle.AnalysisContextBundle.time_axis`): it draws nothing else, so a
    menu offering it over a bundle without one would invite a chart that can only be refused — and the
    refusal costs a paid repair. Off the menu, the contract the response is checked against refuses it too.
    """
    readings = {
        name: reads
        for name, reads in viz_refs.CHART_READINGS.items()
        if time_axis or name not in viz_refs.TIME_VIZ_TYPES
    }
    return ENGINE_CAVEAT_KINDS | profile.caveat_kinds, readings


def _assemble_and_validate(
    result: CompletionResult,
    bundle: AnalysisContextBundle,
    generation: GenerationProvenance,
    profile: HostProfile,
) -> tuple[EvalAnalysis, list[EvalInsight]]:
    """Turn a finished generation into a stored analysis, or refuse it.

    The authored document is checked against the contract it was sent, and its figure references
    are rendered into its prose (:mod:`threetears.evals.analysis.prose_refs`); otherwise it is kept as
    written. What else code fills — every number an evidence reading resolves to, every compiled
    chart — sits beside it on ``resolutions``. Every check here reads a structured field or a
    reference's grammar; none reads the words around one.

    Raises:
        GenerationError: The provider cut the call short (not repaired).
        SoundnessRefusal: The output does not match the contract, a position or reading points
            nowhere, the question answers do not match the declaration, or a decision adopts an arm
            no reading separated from the control (repaired once).
    """
    _reject_incomplete_generation(result)
    payload = _parse_payload(result)
    try:
        document = validate_authored(payload, *_vocabularies(profile, time_axis=bundle.time_axis is not None))
    except (ValidationError, OffVocabulary) as refused:
        raise SoundnessRefusal(f"generator output does not match the analysis contract: {refused}") from refused
    _reject_mismatched_question_answers(document, bundle)
    return _resolved_analysis(document, bundle, generation, bundle_decision_surface(bundle), measures=profile.measures)


def _resolved_analysis(
    document: AuthoredAnalysis,
    bundle: AnalysisContextBundle,
    generation: GenerationProvenance,
    surface: DecisionSurface,
    *,
    measures: MeasureRegistry,
) -> tuple[EvalAnalysis, list[EvalInsight]]:
    """Resolve a validated document's cells, figures and charts against the surface, and build the stored analysis.

    Args:
        document: The validated authored document.
        bundle: The bundle it was generated from.
        generation: The generation's provenance.
        surface: The decision surface its readings resolve against.
        measures: The host's measure registry, which a chart's containment rule reads.

    Returns:
        The stored analysis and the insights it mints.

    Raises:
        SoundnessRefusal: A cell, reading or position points nowhere, one arm is both adopted and
            rejected, or a decision adopts an arm no reading separated from the control (repaired once).
    """
    document = _with_cell_refs(document, surface)
    _reject_contradicted_arms(document, bundle)
    _reject_unseparated_adoptions(document, bundle)
    document = render_prose_figures(document, surface)
    resolutions = [
        _resolution_of(finding, surface, bundle.variant_index, where=f"findings[{index}]", measures=measures)
        for index, finding in enumerate(document.findings)
    ]
    reported = _comparable_measures(bundle.run_summaries)
    all_names = {m.name for summary in bundle.run_summaries for m in summary.measures.measures}
    try:
        analysis = EvalAnalysis(
            campaign_id=bundle.campaign_id,
            subject_id=bundle.subject_id,
            subject_kind=bundle.subject_kind,
            behavior=bundle.behavior,
            observation_refs=bundle.run_ids,
            model_versions=bundle.model_versions,
            scope_id=bundle.scope_id,
            generation=generation,
            design_snapshot=bundle.declared_design,
            document=document,
            resolutions=resolutions,
            judged_tier_rule=JUDGED_TIER_RULE,
            coverage=CoverageLens(levers=[_lever_from_bundle(lever) for lever in bundle.coverage]),
            run_index=[
                _run_index_entry(summary, reported=reported, omitted=sorted(all_names - reported))
                for summary in bundle.run_summaries
            ],
            # Frozen from the bundle, never resolved at read: an analysis must keep saying what its
            # arms WERE, whatever anyone archives or curates afterwards.
            variant_index=bundle.variant_index,
            # The surface every reading was resolved against — the same object, so the stored
            # numbers and the stored facts cannot describe two different bundles.
            decision_surface=surface,
        )
    except ValueError as refused:
        raise SoundnessRefusal(f"generator output failed analysis validation: {refused}") from refused
    return analysis, _insights_of(analysis, bundle, surface)


def _with_cell_refs(document: AuthoredAnalysis, surface: DecisionSurface) -> AuthoredAnalysis:
    """Translate every cell the writer named by alias into the cell's full ``cell_ref``, or refuse one that names none.

    The writer names cells by the short aliases the bundle view showed it; a stored analysis
    carries the full identity, so nothing stored depends on an alias being minted the same way
    again. Translated here, once, before anything is resolved, so every reading, chart and decision
    below this point — and :func:`render_prose_figures`, whose references go through the same
    :func:`~threetears.evals.analysis.references.cell_of_alias` — works on full refs.

    Raises:
        UnresolvableReference: A structured cell field names no cell's alias.
    """

    def ref(alias: str, where: str) -> str:
        try:
            return cell_of_alias(surface, alias)
        except UnresolvableReference as unresolved:
            raise UnresolvableReference(f"{where}: {unresolved}") from unresolved

    findings = [
        finding.model_copy(
            update={
                "evidence": [
                    row.model_copy(update={"cell": ref(row.cell, f"findings[{index}].evidence[{at}]")})
                    for at, row in enumerate(finding.evidence)
                ],
                "chart": finding.chart.model_copy(
                    update={
                        "cells": [
                            ref(cell, f"findings[{index}].chart.cells[{at}]")
                            for at, cell in enumerate(finding.chart.cells)
                        ]
                    }
                ),
            }
        )
        for index, finding in enumerate(document.findings)
    ]
    decisions = [
        decision.model_copy(
            update={"cells": [ref(cell, f"decisions[{index}].cells[{at}]") for at, cell in enumerate(decision.cells)]}
        )
        for index, decision in enumerate(document.decisions)
    ]
    return document.model_copy(update={"findings": findings, "decisions": decisions})


def _reject_mismatched_question_answers(document: AuthoredAnalysis, bundle: AnalysisContextBundle) -> None:
    """Refuse answers that are not exactly one per live declared question.

    A question with no answer reads as one nobody asked, one with two says the analysis reached two
    verdicts over one body of evidence, and an answer to a question the campaign does not ask has
    nothing to attach to. Retired and superseded questions are not live.

    Raises:
        SoundnessRefusal: The answers are not one per live declared question.
    """
    live = bundle.declared_design.live_questions() if bundle.declared_design else []
    declared = {question.id for question in live}
    answered = [answer.question_id for answer in document.questions]
    if duplicates := sorted({qid for qid in answered if answered.count(qid) > 1}):
        raise SoundnessRefusal(f"question(s) {duplicates} are answered more than once; one answer per question")
    if missing := sorted(declared - set(answered)):
        raise SoundnessRefusal(
            f"live declared question(s) {missing} have no answer; `questions` needs one per live question"
        )
    if unknown := sorted(set(answered) - declared):
        raise SoundnessRefusal(
            f"`questions` answers {unknown}, which the campaign does not declare as live"
            + (
                f"; the live questions are {sorted(declared)}"
                if declared
                else "; it declares none, so `questions` is empty"
            )
        )


def _reject_contradicted_arms(document: AuthoredAnalysis, bundle: AnalysisContextBundle) -> None:
    """Refuse an analysis in which one decision adopts an arm and another rejects it.

    The arm table reads each verdict off the cells a decision names, so a memo adopting and rejecting
    one arm states a winner its own decisions also rule out. That is a defect in the memo's structure,
    not a reading of its prose: it is found from dispositions and cell variants alone
    (:func:`~threetears.evals.analysis.arms.contradicted_arms`), and refused through the repair round
    like any other. Runs after cells are translated from aliases, so the refusal names a full ref,
    which the repair round renders back into the writer's alias.

    Raises:
        SoundnessRefusal: Some arm is named by an ``adopted`` and a ``rejected`` decision.
    """
    contradicted = contradicted_arms(document.decisions)
    if not contradicted:
        return
    names = arm_names(bundle.variant_index)
    variant, adopting, rejecting = contradicted[0]
    cell = next(c for c in document.decisions[adopting].cells if variant_of_cell_ref(c) == variant)
    arm = f"the arm at cell {cell}" + (f" ({names[variant]})" if variant in names else "")
    more = f" ({len(contradicted) - 1} other arm(s) likewise)" if len(contradicted) > 1 else ""
    raise SoundnessRefusal(
        f"decisions[{adopting}] adopts {arm} and decisions[{rejecting}] rejects it{more}; one arm takes one "
        "verdict, so keep the decision the findings support and drop or re-scope the other — or, if the "
        "evidence settles neither, mark it `deferred`"
    )


def _reject_unseparated_adoptions(document: AuthoredAnalysis, bundle: AnalysisContextBundle) -> None:
    """Refuse a decision that adopts an arm no reading separated from the control in its favour.

    An ``adopted`` decision makes the arm it names the winner (:func:`~threetears.evals.analysis.arms.arm_table`),
    so it is a claim that the arm beat what it replaces, and ``multiple_comparisons`` is where the bundle
    says whether it did. The arm a decision names is read as the arm table reads it, off each cell's
    variant (:func:`~threetears.evals.analysis.cells.variant_of_cell_ref`), and matched to the
    comparisons whose contrast is that variant, under any rig and in any family.

    One ``improved`` verdict is enough. A trade-off is a legitimate decision: an arm that is cheaper
    and not separated on accuracy, or better on one reading and worse on another, passes. What is
    refused is an adoption with no separated upside: every tested reading ``not_separated``, or
    separated only by ``regressed``, which is evidence against the arm rather than for it. An arm no
    test could reach — the bundle withholds every family, no comparison names it, or each one naming
    it is ``untested`` — has no separation to adopt on either, and is refused saying so, since a
    reader of the arm table cannot tell an adoption resting on nothing from one resting on a test.

    **A breached guardrail refuses the adoption whatever the arm gained** (``bundle.guardrails``): a guardrail
    is what the arm must not get worse on, and it is held, never traded. An undecided guardrail does not
    refuse it — at a few cases and no declared margin almost every guardrail is undecided, so refusing on
    one would refuse nearly every adoption in any campaign that carries a guardrail — and it is never read
    as held either: the report states it on the adopted decision.

    Adopting the declared control (keeping what is there) needs no separation, and a ``rejected`` or
    ``deferred`` decision, or one naming no cell, is not checked. Runs after cells are translated
    from aliases, so it reads full refs; the refusal names them, and the repair round renders them
    back into the writer's aliases.

    Raises:
        SoundnessRefusal: An adopted decision names a non-control arm with a breached guardrail, or with no
            ``improved`` reading.
    """
    control = bundle.declared_design.control if bundle.declared_design else None
    comparisons = bundle.multiple_comparisons
    names = arm_names(bundle.variant_index)
    remedy = "mark it `deferred` with what would settle it in `revisit_when`" + (
        ", or adopt the control" if comparisons.families else ""
    )
    for index, decision in enumerate(document.decisions):
        if decision.disposition != "adopted":
            continue
        arms: dict[str, str] = {}
        for cell in decision.cells:
            variant = variant_of_cell_ref(cell)
            if variant is not None and variant != control:
                arms.setdefault(variant, cell)
        for variant, cell in arms.items():
            arm = f"the arm at cell {cell}" + (f" ({names[variant]})" if variant in names else "")
            if breached := bundle.guardrails.of_arm(variant).breached:
                raise SoundnessRefusal(
                    f"decisions[{index}] adopts {arm}, but it breached the guardrail{'s' if len(breached) > 1 else ''} "
                    f"{', '.join(breached)} (`guardrails`: shown worse than the control by more than the margin), "
                    "and no gain elsewhere pays for a guardrail; mark it `rejected`"
                    + (", or adopt the control" if comparisons.families else "")
                )
            against = [
                comparison
                for family in comparisons.families
                for comparison in family.comparisons
                if comparison.contrast.variant_key == variant
            ]
            if any(comparison.verdict == "improved" for comparison in against):
                continue
            why = _no_separation(against, withheld=comparisons.withheld)
            raise SoundnessRefusal(f"decisions[{index}] adopts {arm}, but {why}; {remedy}")


def _no_separation(against: list[FamilyComparison], *, withheld: str | None) -> str:
    """Say why an arm's comparisons against the control give an adoption nothing to rest on."""
    if withheld is not None:
        return f"the bundle tested no comparison against a control ({withheld.rstrip('.')}), so no test was possible"
    if not against:
        return "no comparison in `multiple_comparisons` tests it against the control, so no test was possible"
    tested = [comparison for comparison in against if comparison.verdict != "untested"]
    if not tested:
        reasons = sorted({comparison.untested_reason or "no reason recorded" for comparison in against})
        return f"no test against the control was possible on any reading ({'; '.join(reasons)})"
    regressed = sorted({comparison.name for comparison in tested if comparison.verdict == "regressed"})
    if regressed:
        return (
            f"it separated from the control only by being worse ({', '.join(regressed)} regressed) "
            "and improved on no reading"
        )
    return "no reading separated it from the control (every tested comparison is `not_separated`)"


def _resolution_of(
    finding: AuthoredFinding,
    surface: DecisionSurface,
    variant_index: list[VariantIndexEntry],
    *,
    where: str,
    measures: MeasureRegistry,
) -> FindingResolution:
    """Fill one finding's numbers and compile its chart.

    Raises:
        UnresolvableReference: A reading names nothing the surface holds, or the chart's lists are not
            the counts its type reads.
    """
    evidence = []
    for index, reading in enumerate(finding.evidence):
        at = f"{where}.evidence[{index}]"
        ref = ReadingRef(measure_id=reading.measure_id, reading=reading.reading)
        resolved = _resolve(surface, reading.cell, ref, where=at)
        evidence.append(
            EvidenceRow(
                cell_ref=reading.cell,
                measure_id=reading.measure_id,
                reading=reading.reading,
                value=resolved.mean,
                n=resolved.n,
                n_cases=resolved.n_cases,
                dispersion=resolved.dispersion,
                judged_tier=resolved.judged_tier,
            )
        )
    chart, note = _compiled_chart(finding.chart, surface, variant_index, where=f"{where}.chart", measures=measures)
    return FindingResolution(evidence=evidence, chart=chart, chart_note=note)


def _compiled_chart(
    chart: AuthoredChart,
    surface: DecisionSurface,
    variant_index: list[VariantIndexEntry],
    *,
    where: str,
    measures: MeasureRegistry,
) -> tuple[Viz | None, str]:
    """Compile the finding's chart, or drop one that cannot be drawn and say so.

    **A compiled chart can still be undrawable** — a breakdown whose categorical measure has one
    category has one part — and refusing the whole paid analysis for one picture discards every
    finding with it. The check is the chart's INTENT (:func:`~threetears.evals.analysis.viz.intent.chart_intent`:
    its payload and the presentation rules), never a renderer's output, so a host drawing with its own
    renderer is held to the same gate. So a chart the presentation rules refuse is dropped, the finding is kept, and
    the reason is recorded beside it (never written into the authored document, which holds only what the model wrote, its figure references rendered)
    and logged at WARNING so the rate is measurable. A reference that points NOWHERE is different:
    that is the model's claim being wrong, and it is refused and repaired.

    Returns:
        The compiled chart, or ``None``; and why a proposed chart was dropped, or an empty string.

    Raises:
        UnresolvableReference: The chart names a cell or reading the surface does not hold, or its
            lists are not the counts its type reads.
    """
    if chart.type == NO_CHART:
        return None, ""
    try:
        reference = viz_refs.reference_from_chart(chart)
        payload = viz_refs.build_viz_payload(reference, surface, variant_index, measures=measures)
    except UnresolvableReference as unresolved:
        raise UnresolvableReference(f"{where} ({chart.type}): {unresolved}") from unresolved
    try:
        chart_intent(chart.type, payload)
    except (PayloadError, IntentPolicyError) as undrawable:
        note = f"A {chart.type} chart was proposed and dropped because it could not be drawn: {undrawable}."
        log.warning("analysis.viz_dropped at=%s type=%s reason=%s", where, chart.type, undrawable)
        return None, note
    viz_type = chart.type
    if not _is_viz_type(viz_type):
        # Unreachable past reference_from_chart, which refuses a type with no reference shape.
        raise UnresolvableReference(f"{where}: {viz_type!r} is not a visualization a finding can carry")
    return Viz(type=viz_type, payload=payload, ref=reference.model_dump(mode="json")), ""


def _is_viz_type(value: str) -> TypeIs[VizType]:
    """Whether ``value`` names a visualization a stored finding can carry."""
    return value in get_args(VizType)


def _insights_of(analysis: EvalAnalysis, bundle: AnalysisContextBundle, surface: DecisionSurface) -> list[EvalInsight]:
    """Mint one durable insight per claim the findings state, citing the runs behind its evidence.

    The model names what is durable; the runs it rests on are read off the cells its evidence cites,
    so an insight cannot cite a run the finding did not. Two findings stating one claim
    (:func:`~threetears.evals.analysis.bundle.insight_restatement_key`) mint it once, from the first.
    Each insight's ``invalidation_trigger`` names what retires it, which the engine carries out:
    archiving this analysis, or a later analysis restating the claim.
    """
    cells = cell_index(surface)
    insights = []
    stated: set[str] = set()
    trigger = (
        f"Retracted if analysis {analysis.id} is archived; replaced in place when a later analysis of this "
        "subject states the same claim."
    )
    for finding in analysis.document.findings:
        if not finding.durable.strip():
            continue
        key = insight_restatement_key(finding.durable)
        if key in stated:
            continue
        stated.add(key)
        runs = sorted({run for row in finding.evidence if row.cell in cells for run in cells[row.cell].run_ids})
        insights.append(
            EvalInsight(
                scope_id=analysis.scope_id,
                subject_id=bundle.subject_id,
                subject_kind=bundle.subject_kind,
                statement=finding.durable,
                confidence=finding.confidence,
                evidence_run_ids=runs,
                model_versions=bundle.model_versions,
                invalidation_trigger=trigger,
                source_campaign_id=bundle.campaign_id,
                source_analysis_id=analysis.id,
            )
        )
    return insights


def first_request(bundle: AnalysisContextBundle, prompt: str, profile: HostProfile) -> tuple[str, str, dict[str, Any]]:
    """The exact first request a generation sends: system prompt, user message and the contract.

    One function, called by :func:`generate_analysis` and by anything that must predict what it will
    send (the capture-replay loop keys its recordings on this), so the two cannot drift. The contract
    is SENT, not described: the provider enforces the shape, and the same models check what comes back.

    Args:
        bundle: The assembled evidence.
        prompt: The resolved generator prompt.
        profile: The host profile the generation runs under.

    Returns:
        ``(system, user, response_format)``.
    """
    contract = response_format(*_vocabularies(profile, time_axis=bundle.time_axis is not None))
    return assemble_system_prompt(prompt, profile), build_user_message(bundle), contract


def build_user_message(bundle: AnalysisContextBundle) -> str:
    """Render the bundle as the user message — the closed system's whole context.

    Public because it has two readers that must agree to the byte: the generator, which sends
    it, and the reporter eval's judge, which scores a memo against exactly what its generator
    was given (:func:`~threetears.evals.analysis.reporter_kind.render_case_material`). A copy of
    the rendering in the second reader would let the judge ground against a bundle the
    generator never saw the moment either one changed.

    The writer reads arms through :func:`~threetears.evals.analysis.arms.writer_arms` in place of
    ``variant_index``: the index is the key's pre-image, hashes and folded surfaces included, and
    stays on the bundle for code to store and join on.

    The writer is shown each family comparison's ADJUSTED p's only (separation and equivalence), and each scope
    divergence's adjusted p. The raw p stays on the bundle for
    audit, but a figure the writer can see is a figure it can quote, and a verdict quoted on the raw
    p of a ten-comparison family is the chance finding the correction exists to stop.

    Args:
        bundle: The assembled context bundle.

    Returns:
        The user message.
    """
    payload = bundle.to_dict()
    del payload["variant_index"]
    # Provenance for code comparing two bundles, and the engine's own retirement rule on each prior insight:
    # nothing the writer can read a finding off, and each one billed on every generation.
    del payload["host_declarations_digest"]
    for insight in payload["prior_insights"]:
        del insight["invalidation_trigger"]
    for family in payload["multiple_comparisons"]["families"]:
        for comparison in family["comparisons"]:
            del comparison["p_raw"]
            del comparison["equivalence_p_raw"]
    for divergence in payload["scope_divergences"]:
        del divergence["p_raw"]
    payload.update(writer_arms(bundle.variant_index))
    _name_cells_by_alias(payload, cell_aliases(bundle.cell_measures))
    return "CONTEXT BUNDLE (JSON):\n" + json.dumps(payload, indent=2, sort_keys=True)


def user_message_digest(message: str) -> str:
    """The digest a generation records of the user message it sent — the one derivation of it.

    :func:`generate_analysis` stores it on the analysis's provenance, and a reporter-case freeze
    computes it over the writer message it is about to freeze and compares, so both must hash the
    same way. The message is text, not a structure: its UTF-8 bytes are hashed as they are, since a
    JSON encoding would address the quoting of the text rather than the text.

    Args:
        message: The user message, exactly as sent (or as about to be frozen).

    Returns:
        A 64-character lowercase hex digest.
    """
    return bytes_digest(message.encode("utf-8"))


def _name_cells_by_alias(payload: dict[str, Any], aliases: dict[str, str]) -> None:
    """Name every cell in the writer's view by its alias, in place.

    A ``cell_measures`` entry is the legend: it gains its ``cell`` and keeps ``variant_key`` (its
    arm, which ``arms`` and the run summaries are keyed by) and ``apparatus_class_id`` (its rig,
    which a refused merge names). Every other object that names a cell by both coordinates — a bar
    verdict, a judged arm, a pooled cell — carries the alias in their place, so the writer joins
    on a short token rather than on two digests. Found by shape rather than by a list of paths, so
    a per-cell record added to the bundle later is named the same way without an edit here.

    Args:
        payload: The bundle as the writer is shown it.
        aliases: The bundle's cell aliases (:func:`~threetears.evals.analysis.references.cell_aliases`).

    Raises:
        RuntimeError: A cell is named that has no ``cell_measures`` entry — the bundle was built
            inconsistently, and the writer could not name that cell at all.
    """
    alias_of = {ref: alias for alias, ref in aliases.items()}
    legend = {id(entry) for entry in payload["cell_measures"]}

    def walk(node: object, path: str) -> None:
        if isinstance(node, list):
            for index, item in enumerate(node):
                walk(item, f"{path}[{index}]")
            return
        if not isinstance(node, dict):
            return
        if "variant_key" in node and "apparatus_class_id" in node:
            alias = alias_of.get(cell_ref(node["variant_key"], node["apparatus_class_id"]))
            if alias is None:
                raise RuntimeError(
                    f"the bundle names a cell at {path} that has no `cell_measures` entry to alias it by"
                )
            if id(node) not in legend:
                del node["variant_key"], node["apparatus_class_id"]
            node["cell"] = alias
        for key, value in node.items():
            walk(value, f"{path}.{key}")

    walk(payload, "")


def assemble_system_prompt(prompt: str, profile: HostProfile) -> str:
    """The resolved prompt, plus the reference grammar code owns and the two things only the host can supply.

    **The figure-reference grammar** (:func:`~threetears.evals.analysis.prose_refs.reference_grammar`).
    The prompt is store-master and the grammar is a code contract, so the grammar is not in the
    prompt: it is appended here, written from the parser's own constants, and so it reaches every
    deployment with the code that enforces it. It follows the resolved prompt directly and says it
    supersedes any other description of the grammar, which is what makes a store prompt that still
    carries an older form harmless rather than a second contract. It precedes the host's lines,
    which qualify the instructions and do not touch the grammar.

    **The style register.** This is the whole of style's reach into a generation, and it is
    deliberately a single concatenation at a single site: the host picked a REGISTER by key and
    the engine supplied the words, so nothing a host wrote is here. That is what keeps the prompt
    pure, and what makes the claim checkable — the prompt-purity test assembles this and proves no host
    free-text value is in it.

    **The host's extra caveat kinds.** A host registers kinds beyond the engine's four so a domain
    with a real fifth kind is not forced to jam it into ``scope``, and the generation-time refusal
    accepts them. Without this line the registration is inert in the one place it matters: the
    model would be refused for a kind it had no way to learn, and every host in the world would
    generate against the engine's four. These are registered identifiers, not prose — the same
    class of thing as a lever name or a measure id, which already ride in the bundle as substance.

    Both go last rather than first, because they qualify instructions that are already complete.
    The analysis's substance — the memo shape, the gates, the posture model, what a caveat
    attaches to — is engine-owned and identical for every host.

    Args:
        prompt: The resolved ``eval_analysis_gen`` system prompt, from the registry.
        profile: The host's profile, for its style's register and its caveat kinds.

    Returns:
        The assembled system prompt.
    """
    assembled = f"{prompt}\n\n{reference_grammar()}\n\nVOICE: {prompt_fragment(profile.style)}"
    if profile.caveat_kinds:
        kinds = ", ".join(sorted(profile.caveat_kinds))
        assembled += (
            f"\n\nCAVEAT KINDS THIS HOST ALSO ACCEPTS, beyond the four above: {kinds}. "
            "Use one when it fits the qualification better than an engine kind does; the engine's four remain "
            "available and nothing else is."
        )
    return assembled


def prompt_content_version(prompt: str, profile: HostProfile, *, time_axis: bool) -> str:
    """The version a generation records for its prompt — a short hash of what the model is told.

    The one derivation of it: :func:`generate_analysis` records it on every analysis it writes, and
    a reporter launch labels its run's subject with it, so a run and the memos it generates name
    one version of one prompt. Over the ASSEMBLED system prompt and the CONTRACT sent with it, not
    the registry text alone: two hosts whose styles picked different registers told the model
    different things, and so do two builds whose schemas differ under one prompt.
    That includes the chart menu, which offers ``timeseries`` only over a bundle with a time axis: the
    model was told a different contract there, so the version says so.

    Args:
        prompt: The resolved ``eval_analysis_gen`` system prompt, from the registry.
        profile: The host's profile, whose register and caveat kinds the assembly adds.
        time_axis: Whether the bundle the prompt is sent with carries a time axis — whether the chart
            menu offered ``timeseries``.

    Returns:
        A stable, edit-sensitive 12-character version tag.
    """
    contract = json.dumps(
        response_format(*_vocabularies(profile, time_axis=time_axis)), sort_keys=True, separators=(",", ":")
    )
    told = assemble_system_prompt(prompt, profile) + "\n" + contract
    return hashlib.sha256(told.encode("utf-8")).hexdigest()[:12]


def _parse_payload(result: CompletionResult) -> dict[str, Any]:
    """Extract the single JSON object the generator returned, or raise.

    ``extract_json`` returns a JSON *object* or raises — a bare array or scalar is
    a ``ValueError`` here, so the object shape is guaranteed to the callers below.

    **Reaching this function means the call finished normally**, so a failure here really
    is a malformed payload and nothing more. That is not an assumption: a provider-reported
    truncation or filter was already refused by :func:`_reject_incomplete_generation`, which
    runs first in :func:`_assemble_and_validate` for exactly this reason. The diagnosis used
    to live here, appended to the parse failure — which reported the cause correctly only
    for the truncations that happen not to parse, and said nothing for the ones that do.
    Reporting only "not valid JSON" on a truncation sent a caller to retry or blame the
    prompt when the fix is the model, while the ``stop_reason="max_tokens"`` sat unread on
    the result. It is now read before the parse, not after it.

    Args:
        result: The completed generator call, known to have finished normally.

    Raises:
        SoundnessRefusal: The content is not a JSON object. Repairable, because the decoder's
            own message names the line and column that broke — an instruction the generator
            can act on. That it is repairable rests on the call having FINISHED, which is the
            guarantee the paragraph above records.
    """
    try:
        return extract_json(result.content or "")
    except ValueError as e:
        raise SoundnessRefusal(f"generator output was not valid JSON: {e}") from e


def _resolve(surface: DecisionSurface, ref: str, reading: ReadingRef, *, where: str) -> ResolvedReading:
    """Resolve one parsed reading through THE lookup, prefixing a refusal with where the reference sat.

    The resolver's own message says what the cell holds, and that is the half the repair round
    needs; this adds which of possibly dozens of references it was about, so the model corrects
    that one rather than guessing.

    Args:
        surface: The analysis's decision surface.
        ref: The reading's ``cell_ref``, translated from the writer's alias.
        reading: The authored reading, already parsed.
        where: Where the reference sits in the output, e.g. ``finding 'f-1' evidence.rows[0]``.

    Returns:
        The resolved reading.

    Raises:
        UnresolvableReference: The reference names nothing the surface holds.
    """
    try:
        return resolve_reading(surface, ref, reading.measure_id, reading.reading)
    except UnresolvableReference as unresolved:
        raise UnresolvableReference(f"{where}: {unresolved}") from unresolved


def _lever_from_bundle(lever: LeverCoverageInput) -> LeverCoverage:
    """Promote a bundle coverage lever to an analysis lever — facts from the bundle.

    Every field comes verbatim from the bundle (never the LLM), so a point estimate always carries its
    sample size and spread. Nothing is added: a lever's coverage is how finely it was swept, and a
    tier looked up from ``status`` would restate ``status`` while reading as a confidence.
    """
    return LeverCoverage(
        name=lever.name,
        cells=lever.cells,
        k=lever.k,
        n=lever.n,
        dispersion=lever.dispersion,
        status=lever.status,
    )


def _comparable_measures(summaries: list[RunSummary]) -> set[str]:
    """Measure names worth a run-index column — those whose value actually differs by run.

    The run index is a COMPARISON table: one row per run, one column per key, and the
    reader scans down a column to see what the config change did. A measure identical in
    every run costs a column and answers nothing there, while the key space itself is
    open — phase timings are ``<tool>_<phase>_ms``, one per tool per phase, growing with
    the system — so without a rule the table widens indefinitely.

    Selecting on variation matches the surface's job, but on its own it does NOT bound the
    table: a phase timing is a continuous float that differs between runs essentially
    always, so variation alone removes none of the growth. A hard cap does the bounding,
    and the two compose — variation decides *which* measures are worth a column, the cap
    decides *how many* a reader can actually scan. Both are disclosed by the caller.

    Ordering under the cap is by **relative spread** (range over typical value), so the
    measures kept are the ones that moved most across the campaign — the ones a reader
    opened the table to find. Ties break on name, so the choice is deterministic and the
    bundle fingerprint stays stable.

    It degenerates correctly: a single-run campaign has nothing to compare, so nothing
    varies and every measure becomes a candidate — ranked and capped by the same rule, here
    rather than in the caller, so the ceiling cannot be routed around by the fallback.

    Args:
        summaries: Every run summary in the campaign.

    Returns:
        The names worth a column, at most ``_MAX_RUN_INDEX_MEASURES`` of them.
    """
    seen: dict[str, set[str]] = {}
    numeric: dict[str, list[float]] = {}
    for summary in summaries:
        for measure in summary.measures.measures:
            # Compare on the rendered value so a float and its repr agree, and so a
            # category-count dict compares by content rather than identity.
            rendered = repr(measure.categories) if measure.categories else repr(measure.bad_tail())
            seen.setdefault(measure.name, set()).add(rendered)
            tail = measure.bad_tail()
            if tail is not None:
                numeric.setdefault(measure.name, []).append(tail)

    varying = {name for name, values in seen.items() if len(values) > 1}
    # Nothing varying means nothing to compare — a single-run campaign, or a campaign whose
    # measures all render identically. Reporting every measure is the right answer there, but
    # it must still go through the cap: the fallback set is the WIDEST one, and phase timings
    # are an open `<tool>_<phase>_ms` name space, so exempting it would let the persisted
    # key_metrics grow without bound on exactly the shape that selects nothing.
    candidates = varying or set(seen)
    if len(candidates) <= _MAX_RUN_INDEX_MEASURES:
        return candidates

    def spread(name: str) -> float:
        values = numeric.get(name) or []
        if not values:
            return 0.0
        typical = max(abs(sum(values) / len(values)), 1e-9)
        return (max(values) - min(values)) / typical

    ranked = sorted(candidates, key=lambda name: (-spread(name), name))
    return set(ranked[:_MAX_RUN_INDEX_MEASURES])


def _run_index_entry(summary: RunSummary, *, reported: set[str], omitted: list[str]) -> RunIndexEntry:
    """Build one run-index row from a bundle run summary (factual, not LLM).

    A numeric measure contributes the tail at its *worse* end — p95 where lower is better,
    p05 where higher is — under a key naming which (the maximum, as ``<name>_max``, where lower is
    better and too few observations give a p95), so a reader is never invited to compare
    a measure's best outcome against another's worst as though both moved the same way. A
    categorical measure contributes its counts.

    Measures identical across every run are left out and **named in ``measures_omitted``**
    rather than silently dropped: a truncated table that does not say what it truncated
    reads as though it covered everything. The full distribution for every measure, omitted
    or not, stays on the bundle, which is what the generator actually reasons over.

    One degenerate case inverts the first sentence: when *nothing* varies there is no
    comparison to make, so identical measures are precisely what gets reported — trimmed to
    the ceiling by relative spread, with whatever the ceiling dropped named in
    ``measures_omitted`` exactly as on the ordinary path.
    """
    # Both cost sides, never one. ``program_cost_usd_floor`` is the blended program total —
    # it includes the judge and simulator scaffolding that exists only to measure the
    # candidate, and it is a floor besides — while the production-replicating figures below
    # describe what the configuration itself spent. Publishing only the first invites a
    # comparison no deployment would pay; publishing only the second hides what the campaign
    # cost to run.
    key_metrics: dict[str, Any] = {
        "n_results": summary.n_results,
        "n_errors": summary.n_errors,
        "program_cost_usd_floor": summary.cost_usd,
    }
    if summary.n_cost_unpriced:
        # The floor leaves these out, so it travels with how many: a run whose candidate ran on an
        # unpriced model is not cheap, its cost is partly unknown.
        key_metrics["n_cost_unpriced"] = summary.n_cost_unpriced
    if summary.prod_cost_usd is not None:
        # The MEAN leads, because it is the figure two runs can be compared on — a total
        # scales with how many results a run produced, so ranking on it ranks run size.
        key_metrics["mean_prod_cost_usd"] = summary.mean_prod_cost_usd
        key_metrics["total_prod_cost_usd"] = summary.prod_cost_usd
        # The denominator travels with the figure: a reader comparing two runs has to be
        # able to see that one of them measured far fewer results than it produced.
        key_metrics["n_prod_cost_usd"] = summary.n_prod_cost_usd
        key_metrics["n_prod_cost_unmeasured"] = summary.n_results - summary.n_prod_cost_usd
        # What the run set away from the subject's production configuration travels with the figure
        # (#571): it is production's cost only for a run that moved nothing, and a caveat printed on
        # every run alike is one a reader stops reading.
        footing = summary.production_footing
        key_metrics["prod_cost_footing"] = (
            "nobody checked which inputs this run moved off the subject's production configuration"
            if footing is None
            else footing.sentence()
        )
        if footing is not None and footing.moved:
            key_metrics["prod_cost_moved_off_production"] = dict(sorted(footing.moved.items()))
        if footing is not None and footing.unchecked:
            key_metrics["prod_cost_unchecked_against_production"] = dict(sorted(footing.unchecked.items()))
    for measure in summary.measures.measures:
        if measure.name not in reported:
            continue
        if measure.categories:
            key_metrics[measure.name] = measure.categories
            continue
        tail = measure.bad_tail()
        if tail is not None:
            key_metrics[f"{measure.name}_p05" if measure.higher_is_better else f"{measure.name}_p95"] = tail
        elif measure.higher_is_better is False and measure.max is not None:
            # Too few observations for a 95th percentile: the slowest seen, named as what it is.
            key_metrics[f"{measure.name}_max"] = measure.max
    if omitted:
        key_metrics["measures_omitted"] = ", ".join(omitted)
    return RunIndexEntry(
        run_id=summary.run_id,
        config=summary.config,
        config_provenance=summary.config_provenance,
        key_metrics=key_metrics,
    )


