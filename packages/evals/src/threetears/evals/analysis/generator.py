"""Closed, one-shot generator: a context bundle → a stored EvalAnalysis.

The productized Analysis lens is generated by a **closed system**:
:func:`generate_analysis` reads a pre-assembled
:class:`~threetears.evals.analysis.bundle.AnalysisContextBundle`, calls the model with a
hot-reloadable prompt (the ``eval_analysis_gen`` type), and returns a schema-valid
:class:`~threetears.evals.kernel.campaign.EvalAnalysis` plus the
:class:`~threetears.evals.kernel.campaign.EvalInsight` objects it minted. No tools, no
network beyond those calls, no fetching — the bundle is the entire evidence set.

**One call, or two.** The generation is one call in the ordinary case and at most two: a
:class:`SoundnessRefusal` — anything a FINISHED call got wrong, whether a rule a claim broke
or a field the payload missed — buys ONE repair round-trip that feeds the refusal back and
regenerates. A second refusal
raises. That bound is the whole design, and both calls are billed and both are recorded:
``GenerationProvenance.repair_attempts`` and ``.repaired_refusal`` put the repair on the
stored artifact, and ``token_cost`` is the total, so a repaired analysis is never mistakable
for one accepted first time. A parse failure and a schema failure ARE repaired, because they
are things a finished call did; only a call that did not finish is not — see
:class:`SoundnessRefusal` for why the boundary sits there and not elsewhere. A generation the provider
reported it cut short does not even reach the chain: :func:`_reject_incomplete_generation`
refuses it first, so a truncation can never buy the repair that would regenerate into the
same cap.

**The contract is sent, not described.** The model is asked for a document in the shape
:mod:`threetears.evals.kernel.authored` defines — headline, summary, findings, decisions, question
answers and next steps — sent as a strict schema (:func:`first_request`) and checked on return by the
same models. The schema types the document's shape and the hooks code acts on, never what it says.

**Facts vs judgment.** The model owns only judgment: what the findings are and what they say, the
decisions and their reasons, the answers, what to run next. The generator fills every fact from the
bundle: the campaign keys, the run index, the coverage levers' n/dispersion/status (a point
estimate always carries its sample size and spread), and the provenance.

**The model names a reading; code fills the number.** Every figure a reader is shown — an evidence
value, n and dispersion, a chart's payload — comes from a reading the model named (a cell and a
measure or judged dimension), resolved against the analysis's decision surface through
:mod:`threetears.evals.analysis.references`. A reading, chart or decision cell naming nothing the surface
holds is an :class:`~threetears.evals.analysis.errors.UnresolvableReference` — a :class:`SoundnessRefusal`,
so it buys the one repair round with the resolver's own account of what does exist. Findings link to
each other by position, which the stored model checks. Confidence is a tier, never a probability.

**What is checked here is STRUCTURE, never prose.**
Every refusal below reads a structured field of the generator's output — a cell or reading it
names, a caveat kind, a question it answers, a position it links — against the bundle. No check parses, pattern-matches or refuses a sentence the model wrote: the
model's prose is the interpretive layer, and whether it is accurate, insightful and relevant is
measured by evaluating the reporter as a candidate, not by code here.

**Closed dependency set.** The generator depends only on the bundle, the
resolved prompt string, the host's profile, and an injected model-provider client (a
:class:`~threetears.evals.schema.completion.CompletionClient`) — never on the runner/simulator/world.
The caller (the host's service layer) resolves the prompt from the registry, builds the client, and
supplies the provenance id of the registry entry it resolved; keeping all three out of here is
what makes a fresh, cheap unit test possible and the extraction seam clean.

The profile is handed in, as the bundle assembler is handed it, so a generation is checked in
exactly one host's vocabulary. Two things need it. The host's style contributes exactly one engine-owned
register fragment to the assembled system prompt (:func:`assemble_system_prompt`), which is the
whole of style's reach into a generation and what the prompt-purity test asserts over. And the
caveat vocabulary a generation is judged against is the engine's four kinds plus whatever this
host registered, so an analysis must be validated against the host it was generated for.
"""

