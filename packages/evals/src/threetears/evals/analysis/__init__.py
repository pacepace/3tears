"""The engine's analysis package: campaigns, context bundles, generated analyses and the read lenses.

It turns a campaign's runs into a generated, stored analysis. Of the engine it imports only itself,
:mod:`threetears.evals.schema` and :mod:`threetears.evals.kernel`, and ships no charting library. The
stored shapes it writes into — the
:class:`~threetears.evals.kernel.campaign.EvalCampaign` hub and the
:class:`~threetears.evals.kernel.campaign.EvalAnalysis` /
:class:`~threetears.evals.kernel.campaign.EvalInsight` documents — live in the kernel,
not here. The pipeline:

- ``reporting``, ``stats`` and ``numbers`` — the query-time projection of runs + results into
  comparable rows, the statistics over them, and how a number is spelled for a reader; beside them the
  disclosures every reader shares (``completeness``, ``significance``, ``measurement_windows``,
  ``cassette_mode``) and the per-result latency split (``latency_partition``).
- ``lenses`` — one module per reporting lens over that projection: comparison sets, pivot, frontier,
  history, the program budget, orphaned runs, export and the cost estimate.
- ``bundle`` — :func:`~threetears.evals.analysis.bundle.assemble.assemble_context_bundle`
  composes the reporting lenses into a deterministic, fingerprintable context bundle; the bundle's schema
  and each family of derivation it composes are modules of that package.
- ``doc_analysis`` — the stored analysis a report document is linked by, and the insights it mints, built once the
  report writer (``analysis_generate``) has stored the document; ``generation_tally`` — what one generation sent,
  spent and was refused, which an attempt's record is stored from.
- ``errors`` — ``UnresolvableReference``, raised where a reference names nothing the decision surface holds, and the
  generation refusals beside it.
- ``report`` — the :class:`~threetears.evals.analysis.report.Report` a campaign is read through: one page,
  verdict first, written by code from the evidence bundle beside it, as Markdown and as HTML (the kit's one
  script drawing its charts, or a static page that runs and loads nothing).
- ``service`` — the operations a client drives the lens with: generating and reading analyses,
  inspecting bundles, reading an analysis as its report, and the insight ledger.
- ``reads`` — the read lenses over runs that already exist: comparison sets, pivot, frontier,
  history, the program budget, orphaned runs, export, the cost estimate, the run summary and the
  two-run comparison (``compare_two_runs``, which ``ops.runs_compare`` exposes).

**This module is the package's public root.** A host imports from here and from no module below
it, and only the names in ``__all__``; ``tests/test_package_matrix.py`` holds that, and
``tests/test_public_surface_is_closed.py`` holds every engine type a public signature hands a host to
being exported from a public root. A ``# debt:`` comment on an export names what retires it. Code
inside the package imports its own modules directly.
"""

