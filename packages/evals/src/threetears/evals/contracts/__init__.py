"""The engine's contracts: the stored shapes, and the vocabulary every other package speaks.

It also holds the derivations over those shapes that need no run-time machinery, and the ports a
host implements — the document store, the completion client, the candidate kind and its cassette
seams. It imports nothing but itself, pydantic and :mod:`threetears.observe` (for logging), which
is what lets ``run``, ``analysis`` and ``gen`` all depend on it without depending on each other.
The host contract a consuming product declares is the sibling root
:mod:`threetears.evals.contracts.host`.

**This module is the package's public root.** A host imports from here and from no module below
it, and only the names in ``__all__``; ``tests/test_package_matrix.py`` holds that, and
``tests/test_public_surface_is_closed.py`` holds every engine type a public signature hands a host to
being exported from a public root. A ``# debt:`` comment on an export names what retires it. Code
inside the package imports its own modules directly.
"""

