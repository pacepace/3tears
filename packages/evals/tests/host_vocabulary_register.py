"""The host-vocabulary ceiling register: every module under ``src/``, and the host terms each may still carry.

Read by ``test_host_vocabulary_ceiling.py``, whose docstring states the terms, how they are matched and
the four ways this register can be wrong. In short:

- **Every module has a row.** The register is total, so a module that lands without one fails by name.
  A row of ``{}`` is a module that names no host, which is where every row is headed.
- **A row lists only the terms a module carries**, each at exactly its count. A term left out is a
  ceiling of 0, and writing ``0`` out is refused, so every state has one spelling.
- **Numbers only fall.** A change that removes host words lowers the ceilings in the same commit: a
  ceiling left above its count fails, because slack is room for the next leak. A change that adds one
  writes it in the engine's own terms instead of raising a number.

Keys are paths relative to ``src/threetears/evals/``. The rows that are not ``{}`` carry ``presence`` in
its ordinary English sense (whether a value is present), which the whole-word count cannot tell apart
from the host noun of the same spelling.
"""

